"""Strictly prospective, read-only forming-candle forecasts from local research models.

Input is generated by a *separate read-only node worker* at the fixed 15s/45s
as-of stages. No label, completed current candle, future bar, broker order
credentials, execution API, or LIVE authorization is accessible here.
"""
from __future__ import annotations
import argparse
import json
import sys
import math
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import load

from scripts.research_forming_candle_learning import (
    ARTIFACT as MODEL_ARTIFACT, FOCUS, FEATURES,
    FRAME_MINUTES, _per_frame_native_candles,
)

ARTIFACT="irexpro-owner-demo-prospective-candle-shadow-v1"
STAGES={"M1":{15,45},"M5":{15,285}}
LABELS={0:"RED_OR_DOWN",1:"COST_SMALL_OR_FLAT",2:"GREEN_OR_UP"}

def utc(v):
    t=pd.Timestamp(v)
    if t.tzinfo is None:
        raise ValueError("UTC_TIMESTAMP_REQUIRED")
    return t.tz_convert("UTC")

def asof_features(snapshot, prior_rows):
    """Reproduce training features using historical bars strictly before barStart."""
    if snapshot.get("artifact")!="irexpro-forming-candle-asof-quote-shadow-v1":
        raise ValueError("INVALID_SNAPSHOT_ARTIFACT")
    if snapshot.get("brokerOrderAuthority") is not False or snapshot.get("modifiesExecution") is not False:
        raise ValueError("SNAPSHOT_MUST_HAVE_NO_TRADE_AUTHORITY")
    if snapshot.get("includesNextBarLabel") is not False or snapshot.get("fromCompletedFutureCandle") is not False:
        raise ValueError("FUTURE_OR_CURRENT_FINISHED_CANDLE_FORBIDDEN")
    if snapshot.get("sourceProvenance")!="ctrader-broker-native-positive-quote-archive":
        raise ValueError("NATIVE_BROKER_ASOF_PROVENANCE_REQUIRED")
    frame=snapshot.get("timeframe")
    inst=snapshot.get("instrument")
    if frame not in STAGES or inst not in FOCUS:
        raise ValueError("UNAPPROVED_INSTRUMENT_OR_TIMEFRAME")
    start=utc(snapshot["barStart"]);at=utc(snapshot["decisionAt"])
    width=pd.Timedelta(minutes=FRAME_MINUTES[frame])
    seconds=(at-start).total_seconds()
    if round(seconds) not in STAGES[frame] or abs(seconds-round(seconds))>.01:
        raise ValueError("PREDECLARED_STAGE_REQUIRED")
    if at>=start+width or at<=start:
        raise ValueError("FINISHED_BAR_NOT_FORMING")
    first=utc(snapshot["firstSourceAt"])
    source=utc(snapshot["lastSourceAt"])
    observed=utc(snapshot["lastObservedAt"])
    if not (start<=first<=source<=observed<=at):
        raise ValueError("FUTURE_QUOTE_NOT_ALLOWED")
    if (first-start).total_seconds()>12 or (observed-source).total_seconds()>10 or (at-observed).total_seconds()>8.5:
        raise ValueError("STALE_OR_LAGGED_QUOTE")
    o,h,l,c=[float(snapshot[k]) for k in ("open","high","low","close")]
    bid,ask,spread=[float(snapshot[k]) for k in ("lastBid","lastAsk","lastSpread")]
    samples=int(snapshot["sampleCount"])
    if not all(math.isfinite(x) for x in (o,h,l,c,bid,ask,spread)) or not (o>0 and l>0 and c>0 and h>=max(o,c) and l<=min(o,c) and ask>bid>0 and spread>0 and samples>=2):
        raise ValueError("INVALID_SAMPLED_CANDLE_GEOMETRY")
    if abs((ask-bid)-spread)>max(1e-7,.05*spread):
        raise ValueError("CROSSED_SPREAD_OR_QUOTE_MISMATCH")
    if not prior_rows:
        raise ValueError("NO_PAST_NATIVE_BARS")
    native=pd.DataFrame(prior_rows)
    for col in ("open","high","low","close"):
        native[col]=pd.to_numeric(native[col],errors="coerce")
    if native[list(("open","high","low","close"))].isna().any().any():
        raise ValueError("INVALID_NATIVE_CONTEXT_OHLC")
    native["bucket_time"]=pd.to_datetime(native["bucket_time"],utc=True)
    if native["bucket_time"].duplicated().any():
        raise ValueError("DUPLICATE_NATIVE_CONTEXT_BARS")
    if not ((native.bucket_time+width)<=start).all():
        raise ValueError("NATIVE_CURRENT_OR_FUTURE_CANDLE_LEAK")
    native=native.sort_values("bucket_time").reset_index(drop=True)
    if native.iloc[-1].bucket_time!=start-width:
        raise ValueError("MOST_RECENT_PRIOR_BAR_MISSING")
    if len(native)<20:
        raise ValueError("INSUFFICIENT_COMPLETED_PREVIOUS_BARS")
    if not ((native.high>=native[["open","close"]].max(axis=1)) &
        (native.low<=native[["open","close"]].min(axis=1)) &
        (native.low>0)).all():
        raise ValueError("INVALID_HISTORICAL_NATIVE_OHLC")
    # A synthetic CURRENT row is used only to compute PREVIOUS-shifted
    # rolling features. Its OHLC is the last earlier completed close, NOT
    # actual/future OHLC or a prediction label.
    prev=float(native.iloc[-1]["close"])
    sentinel=pd.DataFrame([dict(bucket_time=start,open=prev,high=prev,low=prev,close=prev)])
    base=_per_frame_native_candles(pd.concat([native,sentinel],ignore_index=True)
                                   .assign(instrument=inst,timeframe=frame),frame,inst)
    x=base.iloc[-1]
    if not bool(x.prior_fresh) or not math.isfinite(float(x.atr_before)) or x.atr_before<=0:
        raise ValueError("INSUFFICIENT_CAUSAL_ATR_OR_GAPPED_BAR")
    atr=float(x.atr_before)
    rng=max(h-l,1e-10)
    minute=at.hour+at.minute/60
    features=dict(
        instrument_id=float(FOCUS.index(inst)),
        elapsed_fraction=seconds/(width.total_seconds()),
        stage_second=(seconds%60)/60,
        partial_body_atr=(c-o)/atr,
        partial_range_atr=(h-l)/atr,
        upper_wick_fraction=(h-max(o,c))/rng,
        lower_wick_fraction=(min(o,c)-l)/rng,
        close_location=(c-l)/rng,
        spread_atr=spread/atr,
        sample_count_log=math.log1p(samples),
        samples_per_second=samples/max(seconds,1),
        quote_to_previous_close_atr=(c-float(x.previous_close))/atr,
        previous_body_atr=float(x.previous_body_atr),
        previous_range_atr=float(x.previous_range_atr),
        previous_momentum3_atr=float(x.previous_momentum3_atr),
        previous_close_location=float(x.previous_close_location),
        atr_over_price=atr/c,
        hour_sin=math.sin(2*math.pi*minute/24),
        hour_cos=math.cos(2*math.pi*minute/24),
        day_of_week=float(at.dayofweek),
    )
    if sorted(features)!=sorted(FEATURES) or not all(math.isfinite(v) for v in features.values()):
        raise ValueError("UNAVAILABLE_CAUSAL_TRAINING_FEATURE")
    return features

def score_request(request,model_root,training_report,now=None,model_cache=None,report_cache=None):
    now=utc(now or datetime.now(timezone.utc))
    if request.get("mode")!="RESEARCH_ONLY" or request.get("brokerOrderAuthority") is not False:
        raise ValueError("NO_TRADING_AUTHORITY_ALLOWED")
    at=utc(request["decisionAt"])
    if (now-at).total_seconds()<2 or (now-at).total_seconds()>12:
        raise ValueError("NOT_PROSPECTIVE_STAGE_DEADLINE")
    report=report_cache if report_cache is not None else json.loads(Path(training_report).read_text())
    asof=utc(report["asOf"])
    if report.get("artifact")!=MODEL_ARTIFACT or report.get("promotionAllowed") is not False:
        raise ValueError("UNVERIFIED_RESEARCH_MODEL_REPORT")
    if at<=asof+pd.Timedelta(minutes=1):
        raise ValueError("IN_SAMPLE_PREDICTION_REJECTED")
    out=[]
    bundles=model_cache if model_cache is not None else {}
    for snap in request["snapshots"]:
        if snap["decisionAt"]!=request["decisionAt"]:
            raise ValueError("MIXED_ASOF_TIMESTAMPS")
        frame=snap["timeframe"]
        if frame not in STAGES:raise ValueError("UNAPPROVED_TF")
        # Load only the local, owner-controlled serialized research artifact.
        if frame not in bundles:
            bundles[frame]=load(Path(model_root)/f"forming_candle_{frame.lower()}_RESEARCH_ONLY.joblib")
        bundle=bundles[frame]
        if bundle.get("artifact")!=MODEL_ARTIFACT or bundle.get("researchOnly") is not True or bundle.get("noBrokerOrderAuthority") is not True or bundle.get("tf")!=frame:
            raise ValueError("UNTRUSTED_OR_ACTIVE_MODEL")
        if utc(bundle["boundaries"]["secondCutoff"])>=at:
            raise ValueError("MODEL_VALIDATION_BOUNDARY_NOT_BEFORE_FORECAST")
        key=snap["instrument"]+"|"+frame
        native=request.get("priorBars",{}).get(key)
        features=asof_features(snap,native)
        active=bundle["features"]
        X=pd.DataFrame([{name:features[name] for name in active}])
        probabilities=bundle["classifier"].predict_proba(X)[0]
        classes=[int(k) for k in bundle["classifier"].classes_]
        prob={LABELS[k]:round(float(p),6) for k,p in zip(classes,probabilities)}
        best=classes[int(np.argmax(probabilities))]
        out.append({
            "artifact":ARTIFACT,
            "instrument":snap["instrument"],"timeframe":frame,
            "barStart":snap["barStart"],"decisionAt":snap["decisionAt"],
            "predictedNextCandleClass":LABELS[best],
            "rawUncalibratedProbabilities":prob,
            "confidence":round(float(max(probabilities)),6),
            "predictedNextBodyAtr":round(float(max(0,bundle["body"].predict(X)[0])),6),
            "predictedNextRangeAtr":round(float(max(0,bundle["range"].predict(X)[0])),6),
            "observedSpreadPrice":float(snap["lastSpread"]),
            "causalAtrPrice":round(float(snap["lastSpread"])/features["spread_atr"],10),
            "snapshotAgeSeconds":round(float((now-at).total_seconds()),3),
            "modelTrainedAt":report["asOf"],
            "forecastWrittenAt":now.isoformat(),
            "researchOnly":True,"modifiesExecution":False,
            "brokerOrderAuthority":False,
            "nextCandleOutcomeKnown":False,
            "afterCostPnlKnown":False,
        })
    return out

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--request")
    p.add_argument("--models",required=True)
    p.add_argument("--training-report",required=True)
    p.add_argument("--serve",action="store_true")
    args=p.parse_args()
    if args.serve:
        report=json.loads(Path(args.training_report).read_text())
        models={}
        for frame in STAGES:
            models[frame]=load(Path(args.models)/f"forming_candle_{frame.lower()}_RESEARCH_ONLY.joblib")
            b=models[frame]
            if b.get("artifact")!=MODEL_ARTIFACT or b.get("researchOnly") is not True or b.get("noBrokerOrderAuthority") is not True or b.get("tf")!=frame:
                raise ValueError("UNSAFE_RESEARCH_ARTIFACT_NOT_SERVABLE")
        print(json.dumps({"kind":"READY","artifact":ARTIFACT,"tradingAuthority":False}),flush=True)
        for line in sys.stdin:
            msg=None
            try:
                msg=json.loads(line)
                request=msg["request"]
                predictions=score_request(request,args.models,args.training_report,
                                          model_cache=models,report_cache=report)
                result={"kind":"SCORE","id":msg["id"],"artifact":ARTIFACT,
                   "predictions":predictions,"researchOnly":True,
                   "brokerOrderAuthority":False,"modifiesExecution":False}
            except Exception as error:
                result={"kind":"ERROR","id":msg.get("id") if isinstance(locals().get("msg"),dict) else None,
                   "error":str(error)[:220],"tradingAuthority":False}
            print(json.dumps(result),flush=True)
        return
    if not args.request:
        raise ValueError("REQUEST_OR_SERVE_REQUIRED")
    request=json.loads(Path(args.request).read_text())
    predictions=score_request(request,args.models,args.training_report)
    print(json.dumps({"artifact":ARTIFACT,"predictions":predictions,
         "researchOnly":True,"brokerOrderAuthority":False,"modifiesExecution":False}))

if __name__=="__main__":main()
